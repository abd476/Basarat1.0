package com.fyp.basarattradeinvest.data.mapper

import com.fyp.basarattradeinvest.data.remote.dto.recommendations.EngineWeightsResponseDto
import com.fyp.basarattradeinvest.data.remote.dto.recommendations.RecommendationDetailResponseDto
import com.fyp.basarattradeinvest.data.remote.dto.recommendations.RecommendationItemDto
import com.fyp.basarattradeinvest.data.remote.dto.recommendations.TargetStopResponseDto
import com.fyp.basarattradeinvest.domain.model.recommendations.EngineWeights
import com.fyp.basarattradeinvest.domain.model.recommendations.ExpectedPriceRange
import com.fyp.basarattradeinvest.domain.model.recommendations.RecommendationDetail
import com.fyp.basarattradeinvest.domain.model.recommendations.RecommendationSignal
import com.fyp.basarattradeinvest.domain.model.recommendations.StockRecommendation
import com.fyp.basarattradeinvest.domain.model.recommendations.TargetStop

object RecommendationsDtoMapper {

    fun mapRecommendationItem(dto: RecommendationItemDto): StockRecommendation {
        return StockRecommendation(
            symbol = dto.symbol?.uppercase() ?: "UNKNOWN",
            signal = RecommendationSignal.fromString(dto.getResolvedSignal()),
            confidence = dto.getResolvedConfidence(),
            compositeScore = dto.getResolvedCompositeScore(),
            targetPrice = dto.getResolvedTargetPrice(),
            stopLoss = dto.getResolvedStopLoss(),
            summary = dto.summary ?: "AI recommendation generated by BASARAT models",
            currentPrice = dto.getResolvedCurrentPrice()
        )
    }

    fun mapRecommendationDetail(dto: RecommendationDetailResponseDto): RecommendationDetail {
        val rawRange = dto.getResolvedExpectedRange()
        val range = rawRange?.let {
            val low = (it["low"] as? Number)?.toDouble()
                ?: (it["min"] as? Number)?.toDouble()
                ?: 0.0
            val high = (it["high"] as? Number)?.toDouble()
                ?: (it["max"] as? Number)?.toDouble()
                ?: 0.0
            val method = it["method"]?.toString() ?: "atr_range"
            ExpectedPriceRange(low = low, high = high, method = method)
        }

        val mappedReasoning = mutableMapOf<String, Map<String, String>>()
        dto.reasoning?.forEach { (sourceKey, value) ->
            if (value is Map<*, *>) {
                val subMap = mutableMapOf<String, String>()
                value.forEach { (k, v) ->
                    if (k != null && v != null) {
                        subMap[k.toString()] = v.toString()
                    }
                }
                mappedReasoning[sourceKey] = subMap
            } else if (value != null) {
                mappedReasoning[sourceKey] = mapOf("info" to value.toString())
            }
        }

        val summaryText = dto.summary?.takeIf { it.isNotBlank() }
            ?: dto.decision?.reason?.takeIf { it.isNotBlank() }
            ?: "Algorithmic decision support recommendation"
        if (!mappedReasoning.containsKey("ml")) {
            mappedReasoning["ml"] = mapOf("direction" to summaryText)
        }
        if (!mappedReasoning.containsKey("technical")) {
            val techSummary = dto.risk?.explanation?.takeIf { it.isNotBlank() }
                ?: dto.decision?.reason?.takeIf { it.isNotBlank() }
                ?: summaryText
            mappedReasoning["technical"] = mapOf("technical_summary" to techSummary)
        }

        return RecommendationDetail(
            symbol = dto.symbol?.uppercase() ?: "STOCK",
            signal = RecommendationSignal.fromString(dto.getResolvedSignal()),
            confidence = dto.getResolvedConfidence(),
            compositeScore = dto.getResolvedCompositeScore(),
            individualSignals = dto.signals ?: emptyMap(),
            targetPrice = dto.getResolvedTargetPrice(),
            stopLoss = dto.getResolvedStopLoss(),
            expectedRange = range,
            currentPrice = dto.getResolvedCurrentPrice(),
            atr14 = dto.getResolvedAtr14(),
            reasoning = mappedReasoning,
            weights = dto.weights ?: emptyMap()
        )
    }

    fun mapTargetStop(dto: TargetStopResponseDto): TargetStop {
        val rawRange = dto.getResolvedExpectedRange()
        val range = rawRange?.let {
            val low = (it["low"] as? Number)?.toDouble()
                ?: (it["min"] as? Number)?.toDouble()
                ?: 0.0
            val high = (it["high"] as? Number)?.toDouble()
                ?: (it["max"] as? Number)?.toDouble()
                ?: 0.0
            val method = it["method"]?.toString() ?: "atr_range"
            ExpectedPriceRange(low = low, high = high, method = method)
        }

        return TargetStop(
            symbol = dto.symbol.uppercase(),
            currentPrice = dto.getResolvedCurrentPrice(),
            targetPrice = dto.getResolvedTargetPrice(),
            stopLoss = dto.getResolvedStopLoss(),
            expectedRange = range,
            method = dto.getResolvedMethod() ?: "atr_band",
            atr14 = dto.getResolvedAtr14(),
            riskTolerance = dto.getResolvedRiskTolerance() ?: "moderate",
            upsidePct = dto.getResolvedUpsidePct(),
            downsidePct = dto.getResolvedDownsidePct()
        )
    }

    fun mapEngineWeights(dto: EngineWeightsResponseDto): EngineWeights {
        return EngineWeights(
            gruWeight = dto.gruWeight,
            technicalWeight = dto.technicalWeight,
            fundamentalWeight = dto.fundamentalWeight
        )
    }
}
